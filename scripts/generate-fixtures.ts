import fs from "node:fs";
import path from "node:path";
import { epcFor, generateScans, toScanCsv } from "./lib/synthetic";

const dir = path.resolve("tests/fixtures");
fs.mkdirSync(dir, { recursive: true });
const write = (name: string, text: string) => fs.writeFileSync(path.join(dir, name), text);
const E = (i: number) => epcFor("E28011", i);

const base = generateScans({ seed: 1, itemCount: 200 });
const sfRows = base.rows.filter((r) => r.zone === "SALES_FLOOR");
const brRows = base.rows.filter((r) => r.zone === "BACK_ROOM");
write("01_separate_sales_floor.csv", toScanCsv(sfRows, { combined: false, eol: "\r\n" }));
write("01_separate_back_room.csv", toScanCsv(brRows, { combined: false }));
write("02_combined_multi_zone.csv", "﻿" + toScanCsv(base.rows, { combined: true }));
